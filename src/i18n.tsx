const DICTS: Record<Lang, Record<string, string>> = { en, tr };

export function hasKey(key: string): boolean {
  return key in en;
}

/** Translate `key` into `lang`, falling back to English and finally to the key. */
export function translate(lang: Lang, key: string, params?: Params): string {
  const template = DICTS[lang][key] ?? en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export type TFunction = (key: string, params?: Params) => string;

interface I18nValue {
  lang: Lang;
  t: TFunction;
}

const I18nContext = createContext<I18nValue>({ lang: "en", t: (key, params) => translate("en", key, params) });

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const value: I18nValue = { lang, t: (key, params) => translate(lang, key, params) };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
