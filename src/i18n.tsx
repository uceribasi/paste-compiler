// Minimal i18n: two dictionaries, a context/hook for components and a plain
// `translate` function for code outside React.

import { createContext, useContext, type ReactNode } from "react";

export type Lang = "en" | "tr";

export function detectSystemLang(): Lang {
  const nav = typeof navigator !== "undefined" ? navigator.language || "" : "";
  return nav.toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function resolveLang(setting: string | null | undefined): Lang {
  if (setting === "tr") return "tr";
  if (setting === "en") return "en";
  return detectSystemLang();
}

let currentLang: Lang = detectSystemLang();

/** Language used by code that runs outside React (bridge errors, helpers). */
export function getCurrentLang(): Lang {
  return currentLang;
}

export function setCurrentLang(lang: Lang): void {
  currentLang = lang;
}

